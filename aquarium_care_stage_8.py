# === Stage 8: Генерация идентификаторов ===
# Project: AquariumCare
PREFIX = "AQU"


def generate_id(prefix: str, existing: set) -> str:
    """Генерирует уникальный идентификатор с проверкой коллизий.

    Формат: ПРЕФИХ-XXXX, где XXXX — число, увеличивающееся, пока
    сгенерированный идентификатор не станет уникальным относительно
    уже существующих в переданном наборе.

    Args:
        prefix: префикс для сгенерированного идентификатора.
        existing: итерируемый объект с уже использующимися идентификаторами.

    Returns:
        Уникальный идентификатор строкового типа.

    Raises:
        ValueError: если не удалось сгенерировать уникальный идентификатор
            после 100000 попыток (возможно, передан некорректный набор).
    """
    counter = 0
    while counter < 100000:
        counter += 1
        candidate = f"{prefix}-{counter:04d}"
        if candidate not in existing:
            return candidate
    raise ValueError(
        f"Не удалось сгенерировать уникальный идентификатор с префиксом "
        f"'{prefix}' из множества из {len(existing)} элементов"
    )
